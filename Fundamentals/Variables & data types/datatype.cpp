#include <iostream>
using namespace std;

int main() {
    int i = 10;
    float f = 3.14;
    double d = 3.14159;
    char c = 'A';
    bool b = true;
    cout << "Integer: " << i << endl;
    cout << "Float: " << f << endl;
    cout << "Double: " << d << endl;
    cout << "Character: " << c << endl;
    cout << "Boolean: " << b << endl;

    return 0;
}